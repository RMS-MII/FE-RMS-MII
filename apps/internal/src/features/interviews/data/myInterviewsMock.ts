// Mutable store in memory for demo session
let currentMyInterviews = [...initialMyInterviews]

export function getMyInterviews(): MyInterviewItem[] {
  return currentMyInterviews
}

export function updateMyInterviewStatus(
  id: string,
  status: MyInterviewStatus,
  declineReason?: string
): MyInterviewItem | null {
  const target = currentMyInterviews.find((i) => i.id === id)
  if (!target) return null

  target.status = status
  if (declineReason) {
    target.declineReason = declineReason
  }
  return target
}

export function submitMyInterviewAssessment(
  id: string,
  payload: SubmitAssessmentPayload
): MyInterviewItem | null {
  const target = currentMyInterviews.find((i) => i.id === id)
  if (!target) return null

  target.status = "completed"
  target.assessment = {
    id: `ia-${Date.now()}`,
    sessionInterviewId: target.id,
    score: payload.score,
    recommendation: payload.recommendation,
    notes: payload.notes.trim(),
    assessedAt: new Date().toISOString(),
  }
  return target
}

